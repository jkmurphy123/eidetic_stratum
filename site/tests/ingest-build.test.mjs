import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import sharp from 'sharp';
import {ingestBatch} from '../scripts/batch.mjs';
import {checkDist} from '../scripts/check-dist.mjs';

const source=path.resolve(import.meta.dirname,'..');
test('new category and illustrated batch build locally; old URLs persist and missing image blocks build', async t => {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'alderwick-edition-'));
 t.after(() => fs.rmSync(root,{recursive:true,force:true}));
 for (const name of ['src','scripts','content','astro.config.mjs']) fs.cpSync(path.join(source,name),path.join(root,name),{recursive:true});
 fs.mkdirSync(path.join(root,'public/images/articles'),{recursive:true});
 fs.symlinkSync(path.join(source,'node_modules'),path.join(root,'node_modules'),'dir');
 const config=path.join(root,'content/categories.json');
 const categories=JSON.parse(fs.readFileSync(config,'utf8'));
 categories.push({slug:'expedition-notes',label:'Expedition Notes'});
 fs.writeFileSync(config,JSON.stringify(categories));
 const batch=path.join(root,'reviewed-incoming');
 fs.mkdirSync(path.join(batch,'articles'),{recursive:true});
 fs.mkdirSync(path.join(batch,'images'),{recursive:true});
 const id='2026-09-25-test-expedition';
 const src='/images/articles/2026/09/25/test-expedition.png';
 const article={id,slug:'test-expedition',title:'A New Expedition Report',summary:'A new route was charted.',category:'expedition-notes',published_at:'2026-09-25T13:00:00Z',author:'Test Desk',paragraphs:['One.','Two.','Three.','Four.'],tags:['test-expedition'],image:{src,alt:'Test-only synthetic drawing',caption:'Test specimen.',credit:'Test'},related_ids:['2026-09-25-prime-referent-drift']};
 fs.writeFileSync(path.join(batch,'articles/test-expedition.json'),JSON.stringify(article)+'\n');
 const master=path.join(batch,'images/test-expedition.png');
 await sharp({create:{width:900,height:600,channels:3,background:'#bbb'}}).png().toFile(master);
 const manifest={edition_date:'2026-09-25',run_id:'2026-09-25-manual-01',article_ids:[id],assets:[src],validation:{status:'passed',article_count:1}};
 fs.writeFileSync(path.join(batch,'manifest.json'),JSON.stringify(manifest)+'\n');
 const run=(script,args=[]) => execFileSync(script,args,{cwd:root,stdio:'pipe'});
 assert.throws(() => run('node',['scripts/ingest-batch.mjs',batch]),/Command failed/);
 assert.equal(fs.existsSync(path.join(root,'content/batches/2026-09-25.json')),false);
 run('node',['scripts/ingest-batch.mjs',batch,'--accept-reviewed']);
 assert.equal((await ingestBatch(root,batch,{reviewed:true})).status,'unchanged');
 run('node',['scripts/validate-content.mjs']);
 run('node',['scripts/prepare-content.mjs']);
 run(path.join(root,'node_modules/.bin/astro'),['build']);
 assert.deepEqual(checkDist(path.join(root,'dist')),[]);
 const read=file => fs.readFileSync(path.join(root,'dist',file),'utf8');
 assert.match(read('category/expedition-notes/index.html'),/A New Expedition Report/);
 assert.match(read(`articles/${id}/index.html`),/width="900" height="600"/);
 assert.match(read('index.html'),/test-expedition-card\.webp/);
 assert.ok(fs.existsSync(path.join(root,'dist/images/generated',`${id}-card.webp`)));
 assert.ok(fs.existsSync(path.join(root,'dist/articles/2026-09-25-prime-referent-drift/index.html')));
 assert.equal(JSON.parse(read('indexes/search.json')).records.length,58);
 fs.rmSync(path.join(root,'public',src.slice(1)));
 assert.throws(() => run('node',['scripts/validate-content.mjs']),/Command failed/);
 assert.throws(() => run('node',['scripts/prepare-content.mjs']),/Command failed/);
 fs.copyFileSync(master,path.join(root,'public',src.slice(1)));
 const stored=path.join(root,'content/batches/2026-09-25.json');
 fs.writeFileSync(stored,JSON.stringify({...manifest,assets:[]})+'\n');
 assert.throws(() => run('node',['scripts/validate-content.mjs']),/Command failed/);
});
